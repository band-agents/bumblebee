// `drop trigger if exists x on some_table` still errors when some_table itself
// is missing — which on a fresh project it always is. Guard each one.
// Same for `drop policy if exists "name" on some_table`.
const guardTriggerDrops = (sql) =>
  sql
    .replace(/^\s*drop trigger if exists\s+(\w+)\s+on\s+((?:\w+\.)?\w+)\s*;/gim, (_m, trg, tbl) =>
      `do $$ begin if to_regclass('${tbl}') is not null then execute 'drop trigger if exists ${trg} on ${tbl}'; end if; end $$;`)
    .replace(/^\s*drop policy if exists\s+("[^"]+"|\w+)\s+on\s+((?:\w+\.)?\w+)\s*;/gim, (_m, pol, tbl) =>
      `do $$ begin if to_regclass('${tbl}') is not null then execute 'drop policy if exists ${pol.replace(/'/g, "''")} on ${tbl}'; end if; end $$;`);

// schema.sql carries the four POS tables, but they reference `branches`, which
// only exists after advanced-features-foundation.sql. pos-foundation.sql
// creates the same tables (IF NOT EXISTS) with their triggers, RLS and
// policies once branches exists — so the bundle takes them from there.
const POS = ["pos_registers", "pos_transactions", "pos_transaction_items", "branch_inventory"];
function withoutEarlyPos(sql) {
  const start = sql.indexOf("-- ─── pos_registers ─");
  const end = sql.indexOf("-- ===", start);
  if (start < 0 || end < 0) throw new Error("schema.sql POS block markers not found — update build-full-install.mjs");
  let s = sql.slice(0, start) + sql.slice(end);
  s = s.replace(/\s*'pos_registers','pos_transactions','pos_transaction_items','branch_inventory',?/g, "");
  for (const t of POS) s = s.replace(new RegExp(`^alter table ${t}\\s+enable row level security;\\s*$`, "gm"), "");
  // The array lists end with a trailing comma where the POS names were removed.
  s = s.replace(/,(\s*\]\s*loop)/g, "$1");
  return s;
}

// schema.sql also has an early account-based loyalty model. loyalty-foundation.sql
// is the one the app uses (loyalty_members, member_id), with its own RLS and
// policies — but its CREATE TABLE IF NOT EXISTS silently no-ops when schema.sql's
// transactions/rewards/redemptions already exist, and its indexes then fail.
// loyalty_accounts stays: nothing else defines it and nothing conflicts.
function withoutEarlyLoyalty(sql) {
  const start = sql.indexOf("-- ─── loyalty_transactions ─");
  const end = sql.indexOf("-- ─── customer_relationships ─", start);
  if (start < 0 || end < 0) throw new Error("schema.sql loyalty block markers not found — update build-full-install.mjs");
  let s = sql.slice(0, start) + sql.slice(end);
  s = s.replace(/'loyalty_transactions',\s*/g, "").replace(/'loyalty_rewards',\s*/g, "").replace(/'loyalty_redemptions',\s*/g, "");
  return s;
}

let out = "-- Bumblebee full install for a FRESH Supabase project. Generated by scripts/build-full-install.mjs — do not edit.\n";
for (const f of ORDER) {
  let sql = fs.readFileSync(f, "utf8");
  if (f === "schema.sql") sql = withoutEarlyLoyalty(withoutEarlyPos(sql));
  out += `\n\n-- ████ ${f} ████\n` + guardTriggerDrops(sql);
}
fs.writeFileSync("supabase/full-install.sql", out);
console.log(`supabase/full-install.sql: ${ORDER.length} files, ${Buffer.byteLength(out)} bytes`);
