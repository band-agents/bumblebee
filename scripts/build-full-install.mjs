// `drop trigger if exists x on some_table` still errors when some_table itself
// is missing — which on a fresh project it always is. Guard each one.
// Same for `drop policy if exists "name" on some_table`.
const guardTriggerDrops = (sql) =>
  sql
    .replace(/^\s*drop trigger if exists\s+(\w+)\s+on\s+((?:\w+\.)?\w+)\s*;/gim, (_m, trg, tbl) =>
      `do $$ begin if to_regclass('${tbl}') is not null then execute 'drop trigger if exists ${trg} on ${tbl}'; end if; end $$;`)
    .replace(/^\s*drop policy if exists\s+("[^"]+"|\w+)\s+on\s+((?:\w+\.)?\w+)\s*;/gim, (_m, pol, tbl) =>
      `do $$ begin if to_regclass('${tbl}') is not null then execute 'drop policy if exists ${pol.replace(/'/g, "''")} on ${tbl}'; end if; end $$;`);

let out = "-- Bumblebee full install for a FRESH Supabase project. Generated by scripts/build-full-install.mjs — do not edit.\n";
for (const f of ORDER) out += `\n\n-- ████ ${f} ████\n` + guardTriggerDrops(fs.readFileSync(f, "utf8"));
fs.writeFileSync("supabase/full-install.sql", out);
console.log(`supabase/full-install.sql: ${ORDER.length} files, ${Buffer.byteLength(out)} bytes`);
